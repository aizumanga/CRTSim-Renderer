#[cfg(test)]
mod tests {
    use super::*;

    fn tile(shade: u8) -> RgbaImage {
        RgbaImage::from_pixel(64, 48, Rgba([shade, shade, shade, 255]))
    }

    #[test]
    fn tiles_are_laid_out_in_rows_with_their_names_beneath() {
        let tiles = [("A", tile(50)), ("B", tile(100)), ("C", tile(150))];
        let sheet = compose(&tiles, 2).unwrap();
        // Two columns, two rows, 4-pixel gaps and a 16-pixel label strip below each tile.
        assert_eq!(sheet.dimensions(), (2 * 68 + 4, 2 * (48 + 16) + 4));
        assert_eq!(sheet.get_pixel(4, 4), &Rgba([50, 50, 50, 255]));
        assert_eq!(sheet.get_pixel(72, 4), &Rgba([100, 100, 100, 255]));
        assert_eq!(sheet.get_pixel(4, 4 + 64), &Rgba([150, 150, 150, 255]));
        // The empty fourth place is background.
        assert_eq!(sheet.get_pixel(72, 4 + 64), &BACKGROUND);
        // Some of the label beneath the first tile is drawn.
        let label = (4..12).flat_map(|x| (56..64).map(move |y| (x, y)));
        assert!(label
            .into_iter()
            .any(|(x, y)| sheet.get_pixel(x, y) == &TEXT));
    }

    #[test]
    fn names_too_long_end_in_dots_and_unknown_characters_are_question_marks() {
        assert_eq!(fitted("Super Win the Game", 10), "Super W...");
        assert_eq!(fitted("Short", 10), "Short");
        assert_eq!(fitted("Ab", 1), ".");
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph(' '), [0; 8]);
        // 'A': a peak at its top and a crossbar.
        assert_eq!(glyph('A'), [0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]);
    }

    #[test]
    fn mismatched_or_oversized_sheets_are_refused() {
        assert!(compose(&[("A", tile(0)), ("B", RgbaImage::new(10, 10))], 2).is_err());
        assert!(compose(&[], 2).is_err());
        assert!(compose(&[("A", tile(0))], 0).is_err());
        let wide = RgbaImage::new(9000, 10);
        assert!(compose(&[("A", wide.clone()), ("B", wide)], 2).is_err());
    }
}
