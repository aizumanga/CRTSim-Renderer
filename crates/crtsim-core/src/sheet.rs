//! A contact sheet: one picture rendered through many looks, laid out in a grid with each
//! tile labelled with its look's name, to choose between looks at a glance. The labels are drawn
//! in an 8x8 bitmap font, so the sheet needs no font files.
use crate::{config::Config, Renderer, Sequence};
use anyhow::{ensure, Result};
use image::{Rgba, RgbaImage};
use std::sync::atomic::{AtomicBool, Ordering};

/// One look on a sheet: its name, and its settings.
pub struct Look {
    pub name: String,
    pub config: Config,
}

/// The largest sheet made, in pixels per side.
const LARGEST_SIDE: u32 = 16384;
const BACKGROUND: Rgba<u8> = Rgba([16, 35, 55, 255]);
const TEXT: Rgba<u8> = Rgba([220, 233, 246, 255]);

/// `input` rendered through each of `looks` at `tile` pixels, as settled stills, then laid out
/// in rows of `columns`. `rendered` hears how many looks are done, to show progress; `cancel`
/// stops between looks and within one's warm-up.
pub async fn render(
    renderer: &Renderer,
    input: &RgbaImage,
    looks: &[Look],
    tile: (u32, u32),
    columns: u32,
    cancel: Option<&AtomicBool>,
    mut rendered: impl FnMut(usize),
) -> Result<RgbaImage> {
    ensure!(!looks.is_empty(), "A contact sheet needs at least one look");
    let mut tiles = Vec::with_capacity(looks.len());
    for (done, look) in looks.iter().enumerate() {
        let config = Config {
            output: format!("{}x{}", tile.0, tile.1),
            ..look.config.clone()
        };
        config.validate_for(input.dimensions())?;
        ensure!(
            !cancel.is_some_and(|c| c.load(Ordering::Relaxed)),
            "Render cancelled"
        );
        let mut sequence = Sequence::still();
        renderer
            .frame(&mut sequence, input, &config, cancel, |_| {})
            .await?;
        tiles.push((look.name.as_str(), renderer.read(&mut sequence).await?));
        rendered(done + 1);
    }
    compose(&tiles, columns)
}

/// `tiles`, each a name and a picture of one size, in rows of `columns`, each with its name
/// beneath it.
pub fn compose(tiles: &[(&str, RgbaImage)], columns: u32) -> Result<RgbaImage> {
    ensure!(!tiles.is_empty(), "A contact sheet needs at least one tile");
    ensure!(columns > 0, "A contact sheet needs at least one column");
    let (width, height) = tiles[0].1.dimensions();
    ensure!(
        tiles
            .iter()
            .all(|(_, image)| image.dimensions() == (width, height)),
        "Every tile of a contact sheet must be the same size"
    );
    let columns = columns.min(tiles.len() as u32);
    let rows = (tiles.len() as u32).div_ceil(columns);
    // Labels grow with the tiles: 8-pixel glyphs at 1x below 480 pixels wide, 2x below 720…
    let scale = (width / 240).clamp(1, 4);
    let gap = 4 * scale;
    let label = 8 * scale + 2 * gap;
    let sheet_width = u64::from(columns) * u64::from(width + gap) + u64::from(gap);
    let sheet_height = u64::from(rows) * u64::from(height + label) + u64::from(gap);
    ensure!(
        sheet_width <= u64::from(LARGEST_SIDE) && sheet_height <= u64::from(LARGEST_SIDE),
        "The contact sheet would be {sheet_width} x {sheet_height} pixels; make the tiles \
         smaller or use other columns"
    );
    let mut sheet = RgbaImage::from_pixel(sheet_width as u32, sheet_height as u32, BACKGROUND);
    for (n, (name, image)) in tiles.iter().enumerate() {
        let (column, row) = (n as u32 % columns, n as u32 / columns);
        let x = gap + column * (width + gap);
        let y = gap + row * (height + label);
        image::imageops::replace(&mut sheet, image, i64::from(x), i64::from(y));
        let fits = (width / (8 * scale)) as usize;
        draw_text(&mut sheet, &fitted(name, fits), x, y + height + gap, scale);
    }
    Ok(sheet)
}

/// `text` in at most `fits` characters, its end replaced by "..." when it is longer.
fn fitted(text: &str, fits: usize) -> String {
    let characters: Vec<char> = text.chars().collect();
    if characters.len() <= fits {
        return text.to_owned();
    }
    let kept = fits.saturating_sub(3);
    characters[..kept].iter().collect::<String>() + &".".repeat(fits.min(3))
}

/// Draws `text` with its top left at `x`, `y`, each glyph's pixel `scale` pixels square. A
/// character the font lacks is drawn as a question mark.
fn draw_text(image: &mut RgbaImage, text: &str, x: u32, y: u32, scale: u32) {
    for (n, character) in text.chars().enumerate() {
        let glyph = glyph(character);
        let left = x + n as u32 * 8 * scale;
        for (row, bits) in glyph.iter().enumerate() {
            for column in 0..8 {
                if bits >> column & 1 == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (left + column * scale + dx, y + row as u32 * scale + dy);
                        if px < image.width() && py < image.height() {
                            image.put_pixel(px, py, TEXT);
                        }
                    }
                }
            }
        }
    }
}

/// The 8x8 glyph of `character`: eight rows, top first, the lowest bit leftmost.
fn glyph(character: char) -> [u8; 8] {
    let index = match character {
        ' '..='~' => character as usize - 0x20,
        _ => '?' as usize - 0x20,
    };
    FONT[index]
}

